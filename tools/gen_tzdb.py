#!/usr/bin/env python3
"""Generates core/src/tzdb.rs: IANA zone name -> POSIX TZ rule, read from the TZif footers in the system tz database.

Usage: tools/gen_tzdb.py [/usr/share/zoneinfo] > core/src/tzdb.rs
"""
import os, sys, zoneinfo

root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
zones = {}
for name in sorted(zoneinfo.available_timezones()):
    if name.startswith(("posix", "right", "SystemV", "localtime")) or name.endswith(("posixrules", "Factory")):
        continue
    try:
        data = open(os.path.join(root, name), "rb").read()
    except OSError:
        continue
    if data[:4] != b"TZif" or data[4:5] < b"2":
        continue
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode()
    if footer and "\x00" not in footer:
        zones[name] = footer
unique = sorted(set(zones.values()))
index = {p: i for i, p in enumerate(unique)}
version = open(os.path.join(root, "tzdata.zi")).readline().strip() if os.path.exists(os.path.join(root, "tzdata.zi")) else "unknown"
print("// @generated by tools/gen_tzdb.py from the system tz database (%s). Do not edit." % version)
print("// IANA zone name (sorted, ASCII case-insensitive lookup) -> index into `RULES`.")
print("pub static RULES: [&str; %d] = [" % len(unique))
for p in unique:
    print('    "%s",' % p)
print("];")
print("pub static ZONES: [(&str, u16); %d] = [" % len(zones))
for n in sorted(zones, key=str.lower):
    print('    ("%s", %d),' % (n, index[zones[n]]))
print("];")
